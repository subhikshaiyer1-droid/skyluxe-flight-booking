// Helper to look up destination by id
export const getDestinationById = (id) => {
  if (!id) return null;
  return DESTINATIONS.find((d) => d.id.toLowerCase() === id.toLowerCase()) || null;
};

// Helper to get destinations by region
export const getDestinationsByRegion = (region) => {
  if (!region || region === 'All') return DESTINATIONS;
  return DESTINATIONS.filter((d) => d.region.toLowerCase() === region.toLowerCase());
};


export const DOMESTIC_AIRPORTS = AIRPORTS.filter((a) => a.isDomestic);

// Helper to get international airports
export const INTERNATIONAL_AIRPORTS = AIRPORTS.filter((a) => !a.isDomestic);

// Lookup airport by code with resilient fallback
export const getAirportByCode = (code) => {
  if (!code) return null;
  const cleanCode = code.toUpperCase();
  const found = AIRPORTS.find((a) => a.code.toUpperCase() === cleanCode);
  if (found) return found;

  return {
    code: cleanCode,
    city: cleanCode,
    country: 'Global',
    name: `${cleanCode} Airport`,
    flag: '✈️',
    region: 'International',
    isDomestic: false,
    timezone: 'UTC',
    tzOffsetHours: 0
  };
};

// Check if a route is domestic
export const isDomesticRoute = (fromCode, toCode) => {
  const fromAirport = getAirportByCode(fromCode);
  const toAirport = getAirportByCode(toCode);
  return Boolean(fromAirport?.isDomestic && toAirport?.isDomestic);
};
